#!/usr/bin/env python3
"""Generates Sources/DocShot/Design/QuietTokens.swift from Quiet's tokens.json.

Quiet is Noel's design system (~/Documents/quiet-design, skill `quiet-design`). Products hold
only generated tokens, never hand-copied values. Run after Quiet's tokens change:

    python3 Scripts/generate-quiet-tokens.py ~/Documents/quiet-design/artifact/project/tokens.json
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Sources/DocShot/Design/QuietTokens.swift"


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def rgba(hex_value: str) -> str:
    digits = hex_value.lstrip("#")
    if len(digits) == 6:
        digits += "FF"
    if not re.fullmatch(r"[0-9A-Fa-f]{8}", digits):
        raise ValueError(f"not a colour: {hex_value}")
    return "0x" + digits.upper()


def main() -> None:
    source = Path(sys.argv[1]).expanduser()
    tokens = json.loads(source.read_text())
    colours = {t["name"]: t["value"] for t in tokens["color"]["tokens"]}

    def resolve(value: str, mode: str) -> str:
        while value.startswith("{"):
            ref = colours[value.strip("{}")]
            value = ref if isinstance(ref, str) else ref[mode]
        return value

    lines = [
        "// GENERATED by Scripts/generate-quiet-tokens.py from Quiet's tokens.json",
        f"// (version {tokens.get('version')}). Do not edit by hand; regenerate instead.",
        "// Foundation only, so both test targets can check contrast.",
        "",
        "import Foundation",
        "",
        "/// A Quiet colour token: 0xRRGGBBAA for dark and light appearance.",
        "public struct QuietPair: Equatable, Sendable {",
        "    public let dark: UInt32",
        "    public let light: UInt32",
        "",
        "    public init(dark: UInt32, light: UInt32) {",
        "        self.dark = dark",
        "        self.light = light",
        "    }",
        "",
        "    public func value(isDark: Bool) -> UInt32 { isDark ? dark : light }",
        "}",
        "",
        "/// Quiet's tokens as plain values. `Quiet` turns them into SwiftUI colours.",
        "public enum QuietTokens {",
    ]
    for name, value in colours.items():
        if name in ("accent", "accent-hover", "accent-soft", "focus"):
            continue  # the skin: chosen per product in Quiet.swift
        dark = resolve(value if isinstance(value, str) else value["dark"], "dark")
        light = resolve(value if isinstance(value, str) else value["light"], "light")
        lines.append(f"    public static let {camel(name)} = QuietPair(dark: {rgba(dark)}, light: {rgba(light)})")

    # shadow-control as two colours: the 1 px ring (light only) and the 1 px drop shadow.
    control = next(t["value"] for t in tokens["shadow"]["tokens"] if t["name"] == "shadow-control")
    def part(css, pattern):
        found = re.search(pattern, css)
        return rgba(found.group(1)) if found else "0x00000000"
    ring = {m: part(control[m], r"(?<!inset )0 0 0 1px (#[0-9A-Fa-f]{6,8})") for m in ("dark", "light")}
    drop = {m: part(control[m], r"0 1px 2px (#[0-9A-Fa-f]{6,8})") for m in ("dark", "light")}
    lines.append(f"    public static let controlRing = QuietPair(dark: {ring['dark']}, light: {ring['light']})")
    lines.append(f"    public static let controlDrop = QuietPair(dark: {drop['dark']}, light: {drop['light']})")

    lines += ["", "    // Spacing (points)."]
    for t in tokens["spacing"]["tokens"]:
        lines.append(f"    public static let {camel(t['name'])}: Double = {float(t['value'].rstrip('px'))}")
    lines += ["", "    // Radius (points); draw with `style: .continuous`."]
    for t in tokens["radius"]["tokens"]:
        value = t["value"].rstrip("px")
        if value.replace(".", "").isdigit():
            lines.append(f"    public static let {camel(t['name'])}: Double = {float(value)}")
    lines += ["", "    // Durations (seconds)."]
    for t in tokens["duration"]["tokens"]:
        lines.append(f"    public static let {camel(t['name'])}: Double = {int(t['value'].rstrip('ms')) / 1000}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
